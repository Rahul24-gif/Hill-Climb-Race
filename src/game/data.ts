export function getUpgradeCost(category: UpgradeCategory, currentLevel: number): number {
  const base = UPGRADE_INFO[category].baseCost;
  return Math.round(base * Math.pow(1.38, currentLevel - 1));
}

export function getEffectiveVehicleSpec(
  vehicleId: VehicleId,
  upgrades: VehicleUpgradesMap,
  driverId: DriverId = 'rex'
): VehicleSpec {
  const base = VEHICLES[vehicleId];
  const driver = DRIVERS[driverId] || DRIVERS.rex;
  const engBonus = 1 + (upgrades.engine - 1) * 0.085 + driver.torqueBonus;
  const suspBonus = 1 + (upgrades.suspension - 1) * 0.075;
  const tireBonus = 1 + (upgrades.tires - 1) * 0.07 + driver.gripFuelBonus * 0.5;
  const gripBonus = 1 + (upgrades.grip - 1) * 0.075 + driver.gripFuelBonus * 0.5;
  const fuelBonus = 1 + (upgrades.fuel - 1) * 0.12 + driver.gripFuelBonus;
  const airBonus = 1 + (upgrades.airControl - 1) * 0.09 + driver.airSpinBonus;

  return {
    ...base,
    statSpeed: Math.min(100, Math.round(base.statSpeed + (upgrades.engine - 1) * 3.5 + driver.topSpeedBonus * 45)),
    statAcceleration: Math.min(100, Math.round(base.statAcceleration + (upgrades.tires - 1) * 3.5 + driver.torqueBonus * 45)),
    statHandling: Math.min(100, Math.round(base.statHandling + (upgrades.suspension - 1) * 3.2 + driver.bounceToleranceBonus * 45)),
    statFuel: Math.min(100, Math.round(base.statFuel + (upgrades.fuel - 1) * 3.2 + driver.gripFuelBonus * 45)),
    engineTorque: base.engineTorque * engBonus,
    maxWheelOmega: base.maxWheelOmega * (1 + (upgrades.engine - 1) * 0.055 + driver.topSpeedBonus),
    springStiffness: base.springStiffness * suspBonus,
    dampingCoeff: base.dampingCoeff * (1 + (upgrades.suspension - 1) * 0.08),
    suspensionTravel: base.suspensionTravel * (1 + (upgrades.suspension - 1) * 0.03),
    tireGrip: base.tireGrip * tireBonus * gripBonus,
    fuelCapacity: base.fuelCapacity * fuelBonus,
    fuelConsumptionRate: base.fuelConsumptionRate / (1 + (upgrades.fuel - 1) * 0.04 + driver.gripFuelBonus),
    airTorque: base.airTorque * airBonus,
  };
}

